-- Sistema de OS LOKAL: tabelas do Supabase.
-- Como usar: Supabase > SQL Editor > New query > cole este arquivo inteiro > Run. Pode rodar de novo sem estragar nada.
-- Ninguém acessa estas tabelas direto do navegador: só as funções da Vercel, com a chave service_role.
-- Por isso o RLS fica ligado e SEM políticas (a chave pública não lê nem grava nada).

create table if not exists usuarios (
  login        text primary key,              -- andre@lokal, andre1@lokal...
  nome         text not null,
  perfil       text not null check (perfil in ('ADMIN', 'FILIAL', 'MECANICO', 'DIRETORIA')),
  filial       text not null default '',      -- perfil FILIAL: filiais separadas por ;
  equipe       text not null default '',      -- perfil MECANICO
  senha_hash   text not null,
  trocar_senha boolean not null default true,
  ativo        boolean not null default true,
  exemplo      boolean not null default false,
  criado_em    timestamptz not null default now(),
  alterado_em  timestamptz not null default now()
);

create table if not exists veiculos (
  chassi      text primary key,
  frota       text not null default '',
  placa       text not null default '',
  renavam     text not null default '',
  tipo        text not null default '',
  modelo      text not null default '',
  ano         text not null default '',
  empresa     text not null default '',
  responsavel text not null default '',
  filial      text not null,
  obra        text not null default '',
  ativo       boolean not null default true
);
create index if not exists veiculos_placa on veiculos (placa);

create table if not exists os (
  id                  bigint generated by default as identity primary key,
  tipo                text not null check (tipo in ('DIAGNOSTICO', 'SERVICO')),
  status              text not null,
  chassi              text not null references veiculos (chassi),
  placa               text not null default '',
  veiculo             text not null default '',       -- tipo e modelo na data da abertura
  filial              text not null,                  -- filial do veículo NA DATA DA ABERTURA
  local_servico       text not null default '',
  parado              boolean not null default false,
  sintoma             text not null default '',
  grupo               text not null default '',
  servico             text not null default '',
  fotos_problema      text[] not null default '{}',
  aberta_por          text not null,
  aberta_em           timestamptz not null,
  aprovada_por        text, aprovada_em timestamptz,
  devolucao_motivo    text not null default '',
  direcionada_para    text,
  ajudantes           text[] not null default '{}',
  direcionada_por     text, direcionada_em timestamptz,
  iniciada_em         timestamptz,
  executada_em        timestamptz,
  recebida_em         timestamptz,                    -- quando o fechamento chegou ao servidor (pode ser depois, offline)
  km                  numeric, horimetro numeric,
  foto_placa          text, foto_servico text, foto_km text, foto_horimetro text,
  resultado           text,                           -- diagnóstico: RESOLVIDO ou PRECISA_SERVICO
  defeito_encontrado  text not null default '',
  envio_id            text,                           -- identifica o fechamento enviado pelo celular (evita duplicar)
  os_origem           bigint references os (id),      -- OS de serviço gerada a partir de um diagnóstico
  os_servico          bigint references os (id),
  valor_pecas         numeric, valor_mao_obra numeric, valor_deslocamento numeric, valor_total numeric,
  nf_numero           text not null default '', fornecedor text not null default '', nf_arquivo text,
  fechada_por         text, fechada_em timestamptz,
  cancelada_por       text, cancelada_em timestamptz, cancelamento_motivo text not null default '',
  exemplo             boolean not null default false,
  criado_em           timestamptz not null default now(),
  alterado_em         timestamptz not null default now()
);
create index if not exists os_status on os (status);
create index if not exists os_chassi on os (chassi);
create index if not exists os_mecanico on os (direcionada_para);

create table if not exists os_eventos (
  id      bigint generated by default as identity primary key,
  os_id   bigint not null references os (id) on delete cascade,
  etapa   text not null,
  por     text not null,
  em      timestamptz not null default now(),
  obs     text not null default '',
  exemplo boolean not null default false
);
create index if not exists os_eventos_os on os_eventos (os_id);

create table if not exists arquivos (
  caminho     text primary key,                       -- caminho dentro do bucket os-arquivos
  os_id       bigint references os (id) on delete cascade,
  tipo        text not null,
  enviado_por text not null,
  enviado_em  timestamptz not null default now(),
  exemplo     boolean not null default false
);

alter table usuarios   enable row level security;
alter table veiculos   enable row level security;
alter table os         enable row level security;
alter table os_eventos enable row level security;
alter table arquivos   enable row level security;

-- Fotos e notas fiscais: bucket privado (só a chave service_role lê e grava).
insert into storage.buckets (id, name, public, file_size_limit)
values ('os-arquivos', 'os-arquivos', false, 5242880)
on conflict (id) do nothing;
